@invoices_bp.route("/<int:invoice_id>/convert-to-invoice", methods=["POST"])
def convert_to_invoice(invoice_id: int):
    """POST /api/invoices/<id>/convert-to-invoice — convert a quotation to an invoice.

    Rules:
      - Only quotations can be converted (400 if already an invoice).
      - Creates a NEW invoice row with document_type='invoice', keeping all
        items, client, subtotal, vat, total from the quotation.
      - Auto-generates a new INV-YYYY-MM-DD:NNNN number.
      - Decrements inventory for the new invoice (since it's now a sale).
      - Marks the original quotation's status as 'Accepted'.
      - Returns the new invoice.
    """
    quotation = Invoice.query.get(invoice_id)
    if quotation is None:
        return api_response(error="not_found", message=f"No document with id {invoice_id}."), 404

    if quotation.document_type != "quotation":
        return api_response(
            error="invalid_type", message="Only quotations can be converted to invoices."
        ), 400

    # Mark original as accepted
    quotation.status = "Accepted"

    # Create new invoice with same data
    today = date.today()
    new_number = _generate_document_number("invoice", today)

    new_invoice = Invoice(
        document_type="invoice",
        client_id=quotation.client_id,
        lpo_number=quotation.lpo_number,
        invoice_number=new_number,
        issued=today,
        due=quotation.due,
        status="Draft",
        vat_percent=quotation.vat_percent,
        notes=quotation.notes,
        subtotal=quotation.subtotal,
        vat=quotation.vat,
        total=quotation.total,
    )
    for item in quotation.items:
        new_invoice.items.append(InvoiceItem(
            product_name=item.product_name,
            brand=item.brand,
            unit_price=item.unit_price,
            qty=item.qty,
            foc_qty=item.foc_qty,
            discount_percent=item.discount_percent,
            discount_amount=item.discount_amount,
            amount=item.amount,
            vat_percent=item.vat_percent,
            vat_amount=item.vat_amount,
        ))

    db.session.add(new_invoice)
    db.session.flush()

    # Decrement inventory for the new invoice (it's a sale now)
    for item in quotation.items:
        match = Inventory.query.filter(
            func.lower(Inventory.product) == item.product_name.lower()
        ).first()
        if match is not None:
            new_balance = match.balance - item.qty
            match.balance = new_balance if new_balance > 0 else Decimal("0")

    db.session.add(InvoiceAudit(
        invoice_id=new_invoice.id, action="create", field_name=None, old_value=None,
        new_value=f"converted_from_quotation_id={quotation.id}, invoice_number={new_number}",
    ))
    db.session.add(InvoiceAudit(
        invoice_id=quotation.id, action="status_change", field_name="status",
        old_value="Draft", new_value="Accepted",
    ))

    try:
        db.session.commit()
    except IntegrityError:
        db.session.rollback()
        return api_response(
            error="conflict", message=f"Invoice number '{new_number}' already exists (race)."
        ), 409
    except SQLAlchemyError as exc:
        db.session.rollback()
        return api_response(error="db_error", message=str(exc)), 500

    return api_response(data={
        "new_invoice": new_invoice.to_dict(),
        "quotation_id": quotation.id,
    }), 201


