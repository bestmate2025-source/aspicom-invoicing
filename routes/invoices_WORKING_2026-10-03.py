"""Routes for /api/invoices — supports both invoices AND quotations.

Every invoice/quotation's totals are always recomputed server-side from the
items list. Client-sent totals are never trusted.

Document types:
  - document_type='invoice'   — standard sales invoice (has payments)
  - document_type='quotation' — pre-sale quote (no payments, no inventory)

Numbering (auto-generated by the server, never client-supplied):
  Invoices:   INV-YYYY-MM-DD:NNNN  (e.g., INV-2026-10-03:0001)
  Quotations: QTN-YYYY-MM-DD:NNNN  (e.g., QTN-2026-10-03:0001)
  Counter resets daily. Same-day duplicates are handled via retry.

Payment tracking: only allowed on document_type='invoice'.
Inventory: decremented only on document_type='invoice'.

Audit trail: same rules as before — one row per changed field on PUT.
"""

from __future__ import annotations

from datetime import date
from decimal import ROUND_HALF_UP, Decimal, InvalidOperation

from flask import Blueprint, request
from sqlalchemy import func
from sqlalchemy.exc import IntegrityError, SQLAlchemyError

from extensions import db
from models import Client, Inventory, Invoice, InvoiceAudit, InvoiceItem, InvoicePayment
from utils.responses import api_response

invoices_bp = Blueprint("invoices", __name__)
payments_bp = Blueprint("payments", __name__)

ALLOWED_DOCUMENT_TYPES = {"invoice", "quotation"}
INVOICE_STATUSES = {"Draft", "Sent", "Paid", "Overdue"}
QUOTATION_STATUSES = {"Draft", "Sent", "Accepted", "Rejected"}
ALLOWED_PAYMENT_METHODS = {"cash", "bank_transfer", "card", "cheque", "other"}
TOP_LEVEL_EDITABLE_FIELDS = {
    "client_id", "lpo_number", "issued", "due", "valid_until",
    "status", "vat_percent", "notes", "items",
}
AUDITED_SCALAR_FIELDS = (
    "client_id", "lpo_number", "invoice_number", "issued", "due",
    "valid_until", "status", "vat_percent", "notes", "subtotal", "vat", "total",
)
TWO_DP = Decimal("0.01")
HUNDRED = Decimal("100")


# --- small helpers -----------------------------------------------------


def _to_decimal(value, field_name: str) -> Decimal:
    try:
        return Decimal(str(value))
    except (InvalidOperation, TypeError):
        raise ValueError(f"'{field_name}': '{value}' is not a valid number.")


def _quantize(value: Decimal) -> Decimal:
    return value.quantize(TWO_DP, rounding=ROUND_HALF_UP)


def _parse_date(value, field_name: str) -> date | None:
    if value is None:
        return None
    if not isinstance(value, str):
        raise ValueError(f"'{field_name}' must be an ISO date string ('YYYY-MM-DD').")
    try:
        return date.fromisoformat(value)
    except ValueError:
        raise ValueError(f"'{field_name}': '{value}' is not a valid ISO date ('YYYY-MM-DD').")


def _audit_str(value) -> str | None:
    return None if value is None else str(value)


def _allowed_statuses(document_type: str) -> set[str]:
    """Return the valid status set for this document type."""
    return INVOICE_STATUSES if document_type == "invoice" else QUOTATION_STATUSES


def _generate_document_number(document_type: str, issued_date: date | None = None) -> str:
    """Generate the next invoice/quotation number in YYYY-MM-DD:NNNN format.

    Daily reset. Prefixes: INV- for invoices, QTN- for quotations.

    Retries up to 20 times if a race condition creates a duplicate.

    Args:
        document_type: 'invoice' or 'quotation'.
        issued_date: The issued date to use (defaults to today).

    Returns:
        A unique document number like 'INV-2026-10-03:0001'.
    """
    prefix = "INV" if document_type == "invoice" else "QTN"
    d = issued_date or date.today()
    date_part = d.strftime("%Y-%m-%d")
    pattern = f"{prefix}-{date_part}:%"

    for attempt in range(20):
        # Find the highest sequence number for today
        last = (
            Invoice.query
            .filter(Invoice.invoice_number.like(pattern))
            .order_by(Invoice.invoice_number.desc())
            .first()
        )
        if last is None:
            seq = 1
        else:
            try:
                seq = int(last.invoice_number.split(":")[-1]) + 1
            except (ValueError, IndexError):
                seq = 1

        candidate = f"{prefix}-{date_part}:{seq:04d}"
        # Check for collision (shouldn't happen but race conditions possible)
        if Invoice.query.filter_by(invoice_number=candidate).first() is None:
            return candidate
        # Collision — retry with next sequence
    # Fallback: append a random suffix if 20 retries all fail
    import uuid
    return f"{prefix}-{date_part}:{uuid.uuid4().hex[:6]}"


def _items_signature(items) -> list[dict]:
    """Comparable snapshot of an item list for audit diffing."""
    out = []
    for i in items:
        if hasattr(i, "product_name"):
            out.append({
                "product_name": i.product_name,
                "brand": i.brand,
                "unit_price": str(i.unit_price),
                "qty": str(i.qty),
                "foc_qty": str(i.foc_qty),
                "discount_percent": str(i.discount_percent),
                "discount_amount": str(i.discount_amount),
                "amount": str(i.amount),
                "vat_percent": str(i.vat_percent),
                "vat_amount": str(i.vat_amount),
            })
        else:
            out.append({
                "product_name": i.get("product_name"),
                "brand": i.get("brand"),
                "unit_price": str(i.get("unit_price")),
                "qty": str(i.get("qty")),
                "foc_qty": str(i.get("foc_qty")),
                "discount_percent": str(i.get("discount_percent")),
                "discount_amount": str(i.get("discount_amount")),
                "amount": str(i.get("amount")),
                "vat_percent": str(i.get("vat_percent")),
                "vat_amount": str(i.get("vat_amount")),
            })
    return out


def _validate_items_payload(raw_items) -> tuple[list[dict] | None, str | None]:
    """Validate + clean nested items.

    Returns (cleaned_items, None) on success or (None, error_message).
    """
    if not isinstance(raw_items, list) or len(raw_items) == 0:
        return None, "'items' must be a non-empty list."

    cleaned = []
    for idx, raw in enumerate(raw_items):
        if not isinstance(raw, dict):
            return None, f"items[{idx}] must be an object."

        product_name = raw.get("product_name")
        if not isinstance(product_name, str) or not product_name.strip():
            return None, f"items[{idx}].product_name is required and must be a non-empty string."

        brand = raw.get("brand")
        if brand is not None and not isinstance(brand, str):
            return None, f"items[{idx}].brand must be a string."

        if "unit_price" not in raw:
            return None, f"items[{idx}].unit_price is required."
        try:
            unit_price = _to_decimal(raw["unit_price"], f"items[{idx}].unit_price")
        except ValueError as exc:
            return None, str(exc)
        if unit_price < 0:
            return None, f"items[{idx}].unit_price must be >= 0."

        if "qty" not in raw:
            return None, f"items[{idx}].qty is required."
        try:
            qty = _to_decimal(raw["qty"], f"items[{idx}].qty")
        except ValueError as exc:
            return None, str(exc)
        if qty <= 0:
            return None, f"items[{idx}].qty must be > 0."

        try:
            foc_qty = _to_decimal(raw.get("foc_qty", 0), f"items[{idx}].foc_qty")
        except ValueError as exc:
            return None, str(exc)
        if foc_qty < 0:
            return None, f"items[{idx}].foc_qty must be >= 0."

        try:
            discount_percent = _to_decimal(raw.get("discount_percent", 0), f"items[{idx}].discount_percent")
        except ValueError as exc:
            return None, str(exc)
        if not (Decimal("0") <= discount_percent <= HUNDRED):
            return None, f"items[{idx}].discount_percent must be between 0 and 100."

        try:
            vat_percent = _to_decimal(raw.get("vat_percent", 0), f"items[{idx}].vat_percent")
        except ValueError as exc:
            return None, str(exc)
        if not (Decimal("0") <= vat_percent <= HUNDRED):
            return None, f"items[{idx}].vat_percent must be between 0 and 100."

        cleaned.append({
            "product_name": product_name.strip(),
            "brand": brand,
            "unit_price": unit_price,
            "qty": qty,
            "foc_qty": foc_qty,
            "discount_percent": discount_percent,
            "vat_percent": vat_percent,
        })

    return cleaned, None


def _compute_line_amounts(item: dict) -> dict:
    """Given a cleaned item dict, return the fully-calculated amounts."""
    unit_price = item["unit_price"]
    qty = item["qty"]
    discount_percent = item["discount_percent"]
    vat_percent = item["vat_percent"]

    amount = _quantize(unit_price * qty)
    discount_amount = _quantize(amount * discount_percent / HUNDRED)
    taxable = amount - discount_amount
    vat_amount = _quantize(taxable * vat_percent / HUNDRED)

    out = dict(item)
    out["amount"] = amount
    out["discount_amount"] = discount_amount
    out["vat_amount"] = vat_amount
    return out


def _compute_invoice_totals(items_with_amounts: list[dict]) -> tuple[Decimal, Decimal, Decimal]:
    """Return (subtotal, total_discount, total_vat) from fully-calculated items."""
    subtotal = Decimal("0")
    total_discount = Decimal("0")
    total_vat = Decimal("0")
    for item in items_with_amounts:
        subtotal += item["amount"]
        total_discount += item["discount_amount"]
        total_vat += item["vat_amount"]
    return _quantize(subtotal), _quantize(total_discount), _quantize(total_vat)


def _build_invoice_item(calc_item: dict) -> InvoiceItem:
    """Build an InvoiceItem ORM object from a fully-calculated item dict."""
    return InvoiceItem(
        product_name=calc_item["product_name"],
        brand=calc_item["brand"],
        unit_price=calc_item["unit_price"],
        qty=calc_item["qty"],
        foc_qty=calc_item["foc_qty"],
        discount_percent=calc_item["discount_percent"],
        discount_amount=calc_item["discount_amount"],
        amount=calc_item["amount"],
        vat_percent=calc_item["vat_percent"],
        vat_amount=calc_item["vat_amount"],
    )


def _decrement_inventory(cleaned_items: list[dict]) -> None:
    """Best-effort stock decrement, matched by case-insensitive product name.
    Uses only PAID qty (foc_qty does NOT decrement inventory)."""
    for item in cleaned_items:
        match = Inventory.query.filter(
            func.lower(Inventory.product) == item["product_name"].lower()
        ).first()
        if match is None:
            continue
        new_balance = match.balance - item["qty"]
        match.balance = new_balance if new_balance > 0 else Decimal("0")


