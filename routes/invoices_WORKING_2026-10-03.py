@invoices_bp.route("", methods=["GET"])
def list_invoices():
    """GET /api/invoices — list all.

    Query params:
        status — filter by status (validation depends on document_type)
        type   — filter by document_type ('invoice' or 'quotation')
    """
    query = Invoice.query

    type_filter = request.args.get("type")
    if type_filter:
        if type_filter not in ALLOWED_DOCUMENT_TYPES:
            return api_response(
                error="invalid_type", message=f"'type' must be one of {sorted(ALLOWED_DOCUMENT_TYPES)}."
            ), 400
        query = query.filter(Invoice.document_type == type_filter)

    status_filter = request.args.get("status")
    if status_filter:
        # Valid statuses depend on document_type — but we accept any known status
        all_statuses = INVOICE_STATUSES | QUOTATION_STATUSES
        if status_filter not in all_statuses:
            return api_response(
                error="invalid_type", message=f"'status' must be one of {sorted(all_statuses)}."
            ), 400
        query = query.filter(Invoice.status == status_filter)

    invoices = query.order_by(Invoice.created_at.desc()).all()
    return api_response(data=[inv.to_dict() for inv in invoices]), 200


@invoices_bp.route("", methods=["POST"])
def create_invoice():
    """POST /api/invoices — create an invoice OR quotation.

    The document_type field is required. Numbering is auto-generated by the
    server (YYYY-MM-DD:NNNN format, daily reset, INV-/QTN- prefixes).
    """
    body = request.get_json(silent=True)
    if body is None or not isinstance(body, dict):
        return api_response(error="invalid_json", message="Request body must be a JSON object."), 400

    # Document type is required and controls everything else
    document_type = body.get("document_type")
    if document_type not in ALLOWED_DOCUMENT_TYPES:
        return api_response(
            error="missing_field",
            message=f"'document_type' is required and must be one of {sorted(ALLOWED_DOCUMENT_TYPES)}.",
        ), 400

    unknown = set(body.keys()) - TOP_LEVEL_EDITABLE_FIELDS - {"document_type"}
    if unknown:
        return api_response(
            error="unknown_fields", message=f"Unrecognized field(s): {', '.join(sorted(unknown))}."
        ), 400

    client_id = body.get("client_id")
    if not isinstance(client_id, int):
        return api_response(error="missing_field", message="'client_id' is required and must be an integer."), 400

    status = body.get("status", "Draft")
    if status not in _allowed_statuses(document_type):
        return api_response(
            error="invalid_type",
            message=f"'status' for a {document_type} must be one of {sorted(_allowed_statuses(document_type))}.",
        ), 400

    try:
        vat_percent = _to_decimal(body.get("vat_percent", 0), "vat_percent")
    except ValueError as exc:
        return api_response(error="invalid_type", message=str(exc)), 400
    if not (Decimal("0") <= vat_percent <= HUNDRED):
        return api_response(error="invalid_type", message="'vat_percent' must be between 0 and 100."), 400

    try:
        issued = _parse_date(body.get("issued"), "issued")
        due = _parse_date(body.get("due"), "due")
        valid_until = _parse_date(body.get("valid_until"), "valid_until")
    except ValueError as exc:
        return api_response(error="invalid_type", message=str(exc)), 400

    lpo_number = body.get("lpo_number")
    if lpo_number is not None and not isinstance(lpo_number, str):
        return api_response(error="invalid_type", message="'lpo_number' must be a string."), 400

    notes = body.get("notes")
    if notes is not None and not isinstance(notes, str):
        return api_response(error="invalid_type", message="'notes' must be a string."), 400

    cleaned_items, err = _validate_items_payload(body.get("items"))
    if err:
        return api_response(error="invalid_type", message=err), 400

    if Client.query.get(client_id) is None:
        return api_response(
            error="fk_conflict", message=f"No client with id {client_id}. Create the client first."
        ), 409

    # Auto-generate document number based on issued date
    invoice_number = _generate_document_number(document_type, issued)

    calc_items = [_compute_line_amounts(i) for i in cleaned_items]
    subtotal, total_discount, total_vat = _compute_invoice_totals(calc_items)
    total = _quantize(subtotal - total_discount + total_vat)

    invoice = Invoice(
        document_type=document_type,
        client_id=client_id, lpo_number=lpo_number, invoice_number=invoice_number,
        issued=issued, due=due, valid_until=valid_until, status=status,
        vat_percent=vat_percent, notes=notes,
        subtotal=subtotal, vat=total_vat, total=total,
    )
    for calc_item in calc_items:
        invoice.items.append(_build_invoice_item(calc_item))

    db.session.add(invoice)
    db.session.flush()

    db.session.add(InvoiceAudit(
        invoice_id=invoice.id, action="create", field_name=None, old_value=None,
        new_value=f"{document_type}={invoice_number}, total={total}",
    ))

    # Only decrement inventory for actual invoices, not quotations
    if document_type == "invoice":
        _decrement_inventory(cleaned_items)

    try:
        db.session.commit()
    except IntegrityError:
        db.session.rollback()
        return api_response(
            error="conflict",
            message=f"Document number '{invoice_number}' already exists (race with another request).",
        ), 409
    except SQLAlchemyError as exc:
        db.session.rollback()
        return api_response(error="db_error", message=str(exc)), 500

    return api_response(data=invoice.to_dict()), 201


